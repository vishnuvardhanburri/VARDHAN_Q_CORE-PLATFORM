#!/usr/bin/env node
/**
 * Generates contracts/test/fixtures/proofs.json — deterministic Groth16
 * proofs for both M1 circuits, produced by the engine's own prover with the
 * same inputs as the M1 integration tests (producer/consumer symmetry).
 *
 * Each fixture carries the REAL canonical vkHash (keccak256 of the
 * canonical vkey JSON, ADR-0008) so registrations can be replayed 1:1 on
 * Sepolia, and GROTH16 proof fields normalized to Verifier.sol order.
 *
 * Fields are hex-encoded uint256 strings so Foundry's vm.parseJson handles
 * them losslessly.
 */

import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const ENGINE = '/Users/vishnuvardhanburri/zk-proof-engine/packages/engine';
const CIRCUIT_LIB = '/Users/vishnuvardhanburri/zk-proof-engine/packages/circuit-lib';

const { Circuit, prove } = require(`${ENGINE}/dist/index.js`);
const { computeVkHash } = require(`${CIRCUIT_LIB}/dist/index.js`);

const toHex = (v) => `0x${BigInt(v).toString(16)}`;

function vkHashHex(circuitId) {
  const vk = JSON.parse(readFileSync(join(CIRCUIT_LIB, 'build', `${circuitId}.vkey.json`), 'utf8'));
  const hex = computeVkHash(vk).replace(/^0x/, '');
  return `0x${hex.length === 64 ? hex : hex.padStart(64, '0')}`;
}

function shape(proof, publicSignals) {
  return {
    a: [proof.pi_a[0], proof.pi_a[1]].map(toHex),
    // pi_b Fp2 coefficients are serialized imaginary-first by snarkjs; the
    // generated Verifier.sol expects real-first — swap each pair.
    b: [proof.pi_b[0][1], proof.pi_b[0][0], proof.pi_b[1][1], proof.pi_b[1][0]].map(toHex),
    c: [proof.pi_c[0], proof.pi_c[1]].map(toHex),
    publicInputs: publicSignals.map(toHex),
  };
}

async function poseidonFixture() {
  const circuit = await Circuit.load('poseidon-preimage');
  const { proof, publicSignals } = await prove(circuit, { preimage: ['1', '2'] });
  return { circuitId: 'poseidon-preimage', vkHash: vkHashHex('poseidon-preimage'), ...shape(proof, publicSignals) };
}

async function merkleFixture() {
  const circuit = await Circuit.load('merkle-inclusion');
  const { buildPoseidonReference } = require('circomlibjs');
  const p = await buildPoseidonReference();
  const leaves = [];
  for (let i = 0; i < 16; i++) leaves.push(BigInt(p.F.toString(p([BigInt(i), 7n]))));
  const levels = [leaves];
  while (levels[levels.length - 1].length > 1) {
    const prev = levels[levels.length - 1];
    const next = [];
    for (let i = 0; i < prev.length; i += 2) next.push(BigInt(p.F.toString(p([prev[i], prev[i + 1]]))));
    levels.push(next);
  }
  const index = 5;
  const pathBits = [];
  const siblings = [];
  let cur = leaves[index];
  for (let i = 0; i < 4; i++) {
    const pos = index >> i;
    const arr = levels[i];
    const sibling = (pos & 1) === 1 ? arr[pos - 1] : arr[pos + 1];
    pathBits.push(pos & 1);
    siblings.push(sibling.toString());
    cur = BigInt(p.F.toString(p([(pos & 1) === 1 ? sibling : cur, (pos & 1) === 1 ? cur : sibling])));
  }
  const root = levels[4][0];
  const { proof, publicSignals } = await prove(circuit, {
    root: root.toString(),
    leaf: leaves[index].toString(),
    siblings,
    pathBits,
  });
  return { circuitId: 'merkle-inclusion', vkHash: vkHashHex('merkle-inclusion'), ...shape(proof, publicSignals) };
}

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'test', 'fixtures');
mkdirSync(outDir, { recursive: true });
const fixtures = {
  circuits: [await poseidonFixture(), await merkleFixture()],
  note: 'Generated by scripts/gen-proof-fixtures.mjs from the M1 dev PTau + circuit-lib artifacts. Public domain for tests.',
};
writeFileSync(join(outDir, 'proofs.json'), JSON.stringify(fixtures, null, 2));
console.log(`wrote test/fixtures/proofs.json (${fixtures.circuits.length} circuits)`);